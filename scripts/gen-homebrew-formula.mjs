#!/usr/bin/env node
// Emits a Homebrew formula for a published release, ready to submit.
//
//   node scripts/gen-homebrew-formula.mjs 3.0.0
//   node scripts/gen-homebrew-formula.mjs 3.0.0 --sums ./sha256sums.txt
//
// Why this exists: `brew install vibeshield` is the default install path for a
// large fraction of macOS developers, and a formula is a five-minute job once
// you have the four checksums. Fetching and formatting them by hand is the
// reason it does not get done, so this does it.
//
// Two ways to ship the formula, in order of effort:
//
//   1. A tap of your own: create a repository named `homebrew-vibeshield`,
//      drop the generated file at `Formula/vibeshield.rb`, and
//      `brew install <owner>/vibeshield/vibeshield` works immediately.
//   2. homebrew-core: open a PR at https://github.com/Homebrew/homebrew-core
//      with the same file at `Formula/v/vibeshield.rb`. Core has stricter
//      requirements (notability, a stable release history, `brew audit`
//      clean) — read CONTRIBUTING.md there before opening it.
//
// The generator reads the release's own sha256sums.txt, so the formula can
// never carry a checksum for a tarball that was not published.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'rajviyash9136freefr-tech/vibeshield';
const repoRoot = fileURLToPath(new URL('..', import.meta.url));

const args = process.argv.slice(2);
const version = args.find((a) => !a.startsWith('-'));
const sumsIdx = args.indexOf('--sums');
const sumsPath = sumsIdx === -1 ? null : args[sumsIdx + 1];

if (!version || !/^\d+\.\d+\.\d+$/.test(version)) {
  console.error('usage: node scripts/gen-homebrew-formula.mjs <x.y.z> [--sums <sha256sums.txt>]');
  process.exit(2);
}

// --- the four assets a Homebrew formula needs --------------------------------

const ASSETS = {
  darwinArm: `vibeshield-darwin-aarch64.tar.gz`,
  darwinIntel: `vibeshield-darwin-x86_64.tar.gz`,
  linuxArm: `vibeshield-linux-aarch64.tar.gz`,
  linuxIntel: `vibeshield-linux-x86_64.tar.gz`,
};

async function loadSums() {
  if (sumsPath) {
    if (!existsSync(sumsPath)) {
      console.error(`no such file: ${sumsPath}`);
      process.exit(2);
    }
    return readFileSync(sumsPath, 'utf8');
  }
  const url = `https://github.com/${REPO}/releases/download/v${version}/sha256sums.txt`;
  process.stderr.write(`fetching ${url}\n`);
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok) {
    console.error(
      `could not fetch sha256sums.txt for v${version} (HTTP ${res.status}).\n` +
        `Is the release published? Until it is, there is nothing to checksum — ` +
        `generate the formula after tagging, or pass --sums with a local copy.`,
    );
    process.exit(2);
  }
  return res.text();
}

function parseSums(text) {
  const map = {};
  for (const line of text.split('\n')) {
    const parts = line.trim().split(/\s+/);
    if (parts.length >= 2) map[parts[1].replace(/^\*/, '')] = parts[0];
  }
  return map;
}

const sums = parseSums(await loadSums());

const missing = Object.values(ASSETS).filter((a) => !sums[a]);
if (missing.length) {
  console.error(`sha256sums.txt is missing entries for:\n  ${missing.join('\n  ')}`);
  console.error('Check that the release job published all six assets.');
  process.exit(2);
}

const base = `https://github.com/${REPO}/releases/download/v${version}`;
const block = (asset) => `      url "${base}/${asset}"\n      sha256 "${sums[asset]}"`;

const formula = `# Generated by scripts/gen-homebrew-formula.mjs — do not edit by hand.
#
# Regenerate after every release:  node scripts/gen-homebrew-formula.mjs <version>
class Vibeshield < Formula
  desc "Security and dependency auditor for AI-generated code"
  homepage "https://rajviyash9136freefr-tech.github.io/vibeshield/"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block(ASSETS.darwinArm)}
    end
    on_intel do
${block(ASSETS.darwinIntel)}
    end
  end

  on_linux do
    on_arm do
${block(ASSETS.linuxArm)}
    end
    on_intel do
${block(ASSETS.linuxIntel)}
    end
  end

  def install
    bin.install "vibeshield"
    # Tab completion, generated by the binary itself.
    generate_completions_from_executable(bin/"vibeshield", "completion", shells: [:bash, :zsh, :fish])
  end

  test do
    assert_match "vibeshield #{version}", shell_output("#{bin}/vibeshield version")
    assert_match "core", shell_output("#{bin}/vibeshield version")
  end
end
`;

const outPath = join(repoRoot, 'packaging', 'homebrew', 'vibeshield.rb');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, formula);

console.log(`wrote ${outPath}`);
console.log(`\nversion ${version}, checksums from ${sumsPath || 'the published release'}`);
console.log('\nNext:');
console.log('  brew audit --new-formula packaging/homebrew/vibeshield.rb');
console.log('  # own tap:  copy to Formula/vibeshield.rb in a repo named homebrew-vibeshield');
console.log('  # core:     open a PR against Homebrew/homebrew-core at Formula/v/vibeshield.rb');
